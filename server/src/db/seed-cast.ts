import { characters } from '../../../src/mock/characters.ts';
import type { Character } from '../../../src/types/index.ts';

/**
 * The official cast as SQL for `supabase/seed.sql`, made from the app's own mock data so the two
 * never drift (`seed-cast.test.ts` checks the file). Only the officials: user creations live in
 * the database itself. `releasedAt` is left out: the mock sets it relative to today to fill Find's
 * "New" row, which a fixed seed cannot copy.
 */

/** The prompt and profile fields that ride in `characters.persona`, camelCase as in `Character`. */
const PERSONA_KEYS = [
  'tagline',
  'age',
  'heightCm',
  'speakingStyle',
  'look',
  'backstory',
  'likes',
  'dislikes',
  'definition',
  'greetings',
  'starters',
  'temper',
  'role',
  'voicePreset',
] as const satisfies readonly (keyof Character)[];

export const text = (value: string | undefined | null) => (value == null ? 'null' : `'${value.replaceAll("'", "''")}'`);
const textArray = (values: readonly string[]) => (values.length ? `array[${values.map(text).join(', ')}]::text[]` : "'{}'::text[]");

export function personaOf(c: Character): Record<string, unknown> {
  const persona: Record<string, unknown> = {};
  for (const key of PERSONA_KEYS) if (c[key] !== undefined) persona[key] = c[key];
  return persona;
}

function row(c: Character) {
  return `  (${[
    text(c.id),
    text(c.name),
    text(c.handle),
    text(c.bio),
    text(c.category),
    text(c.gender),
    text(c.series),
    String(c.accentIndex),
    String(c.voiceReady),
    text(c.greeting),
    text(c.opening),
    text(c.quirk),
    textArray(c.tags),
    `${text(JSON.stringify(personaOf(c)))}::jsonb`,
  ].join(', ')})`;
}

export const officialCast = () => characters.filter((c) => c.isOfficial);

export function castSeedSql(): string {
  return `-- Generated by \`npm run db:seed-file\` in server/ from src/mock/characters.ts. Do not edit by hand.
-- The official cast (owner_id null, public, approved). Re-running it updates the rows and bumps
-- persona_version when a persona changed.

insert into public.characters
  (id, name, handle, bio, category, gender, series, accent_index, voice_ready, greeting, opening, quirk, tags, persona)
values
${officialCast().map(row).join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  handle = excluded.handle,
  bio = excluded.bio,
  category = excluded.category,
  gender = excluded.gender,
  series = excluded.series,
  accent_index = excluded.accent_index,
  voice_ready = excluded.voice_ready,
  greeting = excluded.greeting,
  opening = excluded.opening,
  quirk = excluded.quirk,
  tags = excluded.tags,
  persona = excluded.persona,
  persona_version = case
    when public.characters.persona is distinct from excluded.persona then public.characters.persona_version + 1
    else public.characters.persona_version
  end;

update public.characters set visibility = 'public', review = 'approved' where owner_id is null;
`;
}
